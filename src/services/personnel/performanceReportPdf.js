// Draws the monthly AI summary as a PDF. jsPDF loads only when a download
// starts (like exceljs in the Excel exports), so pages stay light.
import { downloadBlob, slugFileName } from "../shared/fileDownload.js";
import { buildReportModel, ratingTone } from "./performanceReportRules.js";

const NAVY = [11, 19, 48];
const JADE = [15, 138, 107];
const MUTED = [91, 107, 140];

export async function downloadPerformanceReportPdf(report, profileName) {
  const { jsPDF } = await import("jspdf");
  const model = buildReportModel(report, profileName);
  const tone = ratingTone(model.score);
  const doc = new jsPDF({ unit: "pt", format: "a4" });
  const width = doc.internal.pageSize.getWidth();
  const height = doc.internal.pageSize.getHeight();
  const margin = 48;
  const maxWidth = width - margin * 2;
  let y = 0;

  const ensureSpace = (needed) => {
    if (y + needed > height - 64) {
      doc.addPage();
      y = margin;
    }
  };

  // Header band
  doc.setFillColor(...NAVY);
  doc.rect(0, 0, width, 96, "F");
  doc.setTextColor(255, 255, 255);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(18);
  doc.text("Monthly Performance Summary", margin, 44);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(11);
  doc.text(`${model.person} · ${model.month}`, margin, 68);
  y = 128;

  // Rating badge
  doc.setFillColor(...tone.pdfBg);
  doc.roundedRect(margin, y - 18, 240, 32, 8, 8, "F");
  doc.setTextColor(...tone.pdfFg);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(13);
  doc.text(`${model.label} — ${model.score}/100`, margin + 14, y + 3);
  y += 46;

  // Trend against their own previous months
  if (model.trend) {
    doc.setFont("helvetica", "normal");
    doc.setFontSize(10);
    doc.setTextColor(...MUTED);
    doc.text(`Compared with their previous months: ${model.trend}`, margin, y);
    y += 20;
  }

  // Headline
  doc.setTextColor(...NAVY);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(12.5);
  const headline = doc.splitTextToSize(model.headline, maxWidth);
  ensureSpace(headline.length * 17 + 12);
  doc.text(headline, margin, y);
  y += headline.length * 17 + 12;

  // Paragraphs
  doc.setFont("helvetica", "normal");
  doc.setFontSize(10.5);
  for (const paragraph of model.paragraphs) {
    const lines = doc.splitTextToSize(paragraph, maxWidth);
    ensureSpace(lines.length * 15 + 10);
    doc.text(lines, margin, y);
    y += lines.length * 15 + 10;
  }

  // Sections
  for (const section of model.sections) {
    ensureSpace(34);
    doc.setFont("helvetica", "bold");
    doc.setFontSize(12);
    doc.setTextColor(...JADE);
    doc.text(section.title, margin, y);
    y += 17;
    doc.setFont("helvetica", "normal");
    doc.setFontSize(10.5);
    doc.setTextColor(...NAVY);
    for (const item of section.items) {
      const lines = doc.splitTextToSize(`•  ${item}`, maxWidth - 6);
      ensureSpace(lines.length * 15 + 6);
      doc.text(lines, margin + 6, y);
      y += lines.length * 15 + 6;
    }
    y += 8;
  }

  // Stats box
  if (model.stats.length > 0) {
    const boxHeight = 34 + model.stats.length * 15;
    ensureSpace(boxHeight + 16);
    doc.setFillColor(247, 246, 251);
    doc.roundedRect(margin, y - 12, maxWidth, boxHeight, 8, 8, "F");
    doc.setFont("helvetica", "bold");
    doc.setFontSize(10.5);
    doc.setTextColor(...NAVY);
    doc.text("Month at a glance", margin + 14, y + 10);
    y += 26;
    doc.setFont("helvetica", "normal");
    for (const [label, value] of model.stats) {
      doc.setTextColor(...MUTED);
      doc.text(String(label), margin + 14, y);
      doc.setTextColor(...NAVY);
      doc.text(String(value), margin + 240, y);
      y += 15;
    }
    y += 12;
  }

  // Footer on every page
  const pages = doc.getNumberOfPages();
  for (let page = 1; page <= pages; page++) {
    doc.setPage(page);
    doc.setFont("helvetica", "normal");
    doc.setFontSize(8);
    doc.setTextColor(...MUTED);
    doc.text(
      "Generated by AI from the system activity log — a guide for review, not a final judgment.",
      margin,
      height - 34,
    );
    doc.text(
      `${model.model || "AI"} · Page ${page} of ${pages}`,
      margin,
      height - 22,
    );
  }

  downloadBlob(
    doc.output("blob"),
    `performance-${slugFileName(model.person)}-${model.monthValue || "report"}.pdf`,
  );
}
