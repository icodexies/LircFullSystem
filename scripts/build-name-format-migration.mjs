// One-off generator: rebuild every current RPC that concatenates user names so
// it uses lirc_private.person_name (Surname, Firstname M.). Prints the plan;
// writes the migration only with --write.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = "supabase/migrations";
const files = readdirSync(dir)
  .filter((f) => f.endsWith(".sql"))
  .filter((f) => !f.startsWith("20261020110000"))
  .sort();
const defs = new Map();
let found = 0;

for (const file of files) {
  const text = readFileSync(join(dir, file), "utf8");
  const re = /create\s+or\s+replace\s+function\s+((?:public|lirc_private)\."?\w+"?)\s*\(/gi;
  let m;
  while ((m = re.exec(text)) !== null) {
    const start = m.index;
    const paren = re.lastIndex - 1;
    let depth = 0;
    let close = -1;
    for (let i = paren; i < text.length && i < paren + 4000; i += 1) {
      if (text[i] === "(") depth += 1;
      else if (text[i] === ")") {
        depth -= 1;
        if (depth === 0) {
          close = i;
          break;
        }
      }
    }
    if (close === -1) break;
    const asMatch = /\bas\s+(\$[A-Za-z_]*\$)/i.exec(text.slice(close + 1, close + 600));
    if (!asMatch) {
      re.lastIndex = close + 1;
      continue;
    }
    const delim = asMatch[1];
    const bodyStart = close + 1 + asMatch.index + asMatch[0].length;
    const bodyEnd = text.indexOf(delim + ";", bodyStart);
    if (bodyEnd === -1) break;
    const end = bodyEnd + delim.length + 1;
    const qualifier = m[1].replace(/"/g, "");
    const argsRaw = text.slice(paren, close + 1).replace(/\s+/g, " ").toLowerCase();
    defs.set(qualifier.toLowerCase() + argsRaw, {
      key: qualifier.toLowerCase() + argsRaw,
      qualifier,
      chunk: text.slice(start, end),
      file,
    });
    found += 1;
    re.lastIndex = end;
  }
}

function replaceNames(chunk, changes) {
  let out = chunk;
  const patterns = [
    /concat_ws\(\s*' '\s*,\s*(\w+)\.first_name\s*,\s*\1\.middle_initial\s*,\s*\1\.surname\s*,\s*\1\.suffix\s*\)/g,
    /concat_ws\(\s*' '\s*,\s*(\w+)\.first_name\s*,\s*\1\.middle_initial\s*,\s*\1\.surname\s*\)/g,
    /concat_ws\(\s*' '\s*,\s*(\w+)\.first_name\s*,\s*\1\.surname\s*\)/g,
    /concat_ws\(\s*' '\s*,\s*(\w+)\.surname\s*\|\|\s*','\s*,\s*\1\.first_name\s*,\s*\1\.middle_initial\s*,\s*\1\.suffix\s*\)/g,
    /concat_ws\(\s*' '\s*,\s*(\w+)\.surname\s*,\s*\1\.first_name\s*,\s*\1\.middle_initial\s*,\s*\1\.suffix\s*\)/g,
  ];
  for (const re of patterns) {
    out = out.replace(re, (match, alias, offset) => {
      const before = out.slice(Math.max(0, offset - 8), offset);
      const after = out.slice(offset + match.length, offset + match.length + 24);
      if (/lower\(\s*$/.test(before)) return match;
      if (/^\s*(?:ilike|like)\b/i.test(after)) return match;
      changes.push(alias);
      // The text overload works for usersData rows, profile_dimensions rows
      // and subquery records alike.
      return `lirc_private.person_name(${alias}.first_name, ${alias}.middle_initial, ${alias}.surname, ${alias}.suffix)`;
    });
  }
  // Loan records build the name with trimmed parts; same result, same formatter.
  out = out.replace(
    /concat_ws\(\s*' '\s*,\s*(\w+)\.first_name\s*,\s*nullif\(btrim\(coalesce\(\1\.middle_initial, ''\)\), ''\)\s*,\s*\1\.surname\s*,\s*nullif\(btrim\(coalesce\(\1\.suffix, ''\)\), ''\)\s*\)/g,
    (match, alias) => {
      changes.push(alias);
      return `lirc_private.person_name(${alias}.first_name, ${alias}.middle_initial, ${alias}.surname, ${alias}.suffix)`;
    },
  );
  return out;
}

const changed = [];
for (const def of defs.values()) {
  if (/goal/i.test(def.qualifier)) continue; // the goals feature was removed
  const changes = [];
  const next = replaceNames(def.chunk, changes);
  if (changes.length) changed.push({ ...def, chunk: next, count: changes.length });
}

console.log(`definitions found: ${found}; latest tracked: ${defs.size}`);
console.log(`functions with name concatenations: ${changed.length}`);
for (const c of changed) console.log(`  ${c.qualifier} (${c.count})  ← ${c.file}`);

if (process.argv.includes("--write")) {
  const header = `-- ============================================================================
-- Display names: every record and table shows "Surname, Firstname M.".
--
-- The name-building concatenations in these response functions are replaced
-- with lirc_private.person_name (the same formatter the station and the desk
-- scanner already use). Search predicates keep matching the space-separated
-- form, so typing "Sam Villanueva" still finds the record.
--
-- Generated by scripts/build-name-format-migration.mjs from the current
-- definitions; only the name expressions change.
-- ============================================================================
begin;

-- Text flavour of the formatter for subquery rows (which are not usersData
-- composites), e.g. the statistics top-borrower lists.
create or replace function lirc_private.person_name(
  p_first text,
  p_middle text,
  p_surname text,
  p_suffix text default null)
returns text
language plpgsql
immutable
security definer
set search_path = ''
as $$
declare
  mi text;
  given text;
  base text;
begin
  mi := nullif(btrim(coalesce(p_middle, '')), '');
  if mi is not null and right(mi, 1) <> '.' then
    mi := mi || '.';
  end if;
  given := nullif(concat_ws(' ', nullif(btrim(coalesce(p_first, '')), ''), mi), '');
  base := concat_ws(', ', nullif(btrim(coalesce(p_surname, '')), ''), given);
  return nullif(concat_ws(' ', base, nullif(btrim(coalesce(p_suffix, '')), '')), '');
end $$;
revoke all on function lirc_private.person_name(text, text, text, text)
  from public, anon, authenticated;
`;
  const parts = changed.map((c) => `-- ${c.qualifier}\n${c.chunk}\n`);
  const footer = "\nnotify pgrst, 'reload schema';\ncommit;\n";
  writeFileSync(
    "supabase/migrations/20261020110000_display_names_everywhere.sql",
    header + "\n" + parts.join("\n") + footer,
  );
  console.log("written: supabase/migrations/20261020110000_display_names_everywhere.sql");
}
