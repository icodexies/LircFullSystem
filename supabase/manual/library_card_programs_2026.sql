create temp table _preview (item text, detail text);
insert into _preview
select 'file.cards', count(*)::text from _card_programs
union all
select 'db.students_total', count(*)::text from public."usersData"
 where lower(btrim(role::text)) = 'student'
union all
select 'db.students_no_program', count(*)::text from public."usersData"
 where lower(btrim(role::text)) = 'student' and program_id is null
union all
select 'matched.students', count(*)::text
 from public."usersData" u join _card_programs c on c.card = u.library_id
 where lower(btrim(u.role::text)) = 'student'
union all
select 'to_assign.unassigned', count(*)::text
 from public."usersData" u join _card_programs c on c.card = u.library_id
 where lower(btrim(u.role::text)) = 'student' and u.program_id is null
union all
select 'to_fix.conflicts', count(*)::text
 from public."usersData" u join _card_programs c on c.card = u.library_id
 join public.programs p on p.id = u.program_id
 where lower(btrim(u.role::text)) = 'student' and p.name <> c.code
union all
select 'already_correct', count(*)::text
 from public."usersData" u join _card_programs c on c.card = u.library_id
 join public.programs p on p.id = u.program_id
 where lower(btrim(u.role::text)) = 'student' and p.name = c.code
union all
select 'matched.nonstudents', count(*)::text
 from public."usersData" u join _card_programs c on c.card = u.library_id
 where lower(btrim(u.role::text)) <> 'student'
union all
select 'file.cards_not_in_db', count(*)::text
 from _card_programs c
 where not exists (select 1 from public."usersData" u where u.library_id = c.card)
union all
select 'unknown_codes', coalesce(string_agg(distinct c.code, ', '), 'none')
 from _card_programs c
 where not exists (select 1 from public.programs p where p.name = c.code)
union all
select 'course_spread', coalesce((
  select string_agg(x.detail, ' | ') from (
    select c.code || ' ×' || count(*) as detail
    from _card_programs c group by c.code order by count(*) desc) x), '-');


