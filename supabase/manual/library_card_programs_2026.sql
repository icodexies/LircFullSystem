update public."usersData" u
   set program_id = p.id,
       department_id = p.department_id
  from _card_programs c
  join public.programs p on p.name = c.code
 where c.card = u.library_id
   and lower(btrim(u.role::text)) = 'student'
   and (u.program_id is null
        or u.program_id <> p.id
        or u.department_id is distinct from p.department_id);
