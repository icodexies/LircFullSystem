-- ============================================================================
-- Registration claim tokens
--
-- A public visitor requests a registration link with their CCC email. The
-- emailed link carries a random token; only its SHA-256 hash is stored here.
-- The token is bound to the email, expires after 30 minutes, and becomes used
-- once the account is created. The roster profile is attached only after the
-- visitor proves the library ID + name match.
--
-- The service-role edge function is the only writer/reader. No public or
-- authenticated PostgREST access is granted.
-- ============================================================================
begin;

create table if not exists public.registration_tokens (
  id bigint generated by default as identity primary key,
  email text not null check (email = lower(email) and email ~ '^[^@\s]+@ccc\.edu\.ph$'),
  token_hash text not null unique,
  profile_id bigint references public."usersData"(id) on delete cascade,
  identity_verified_at timestamptz,
  expires_at timestamptz not null,
  used_at timestamptz,
  created_at timestamptz not null default now()
);

create index if not exists registration_tokens_email_created_idx
  on public.registration_tokens (email, created_at desc);
create index if not exists registration_tokens_expires_idx
  on public.registration_tokens (expires_at);

alter table public.registration_tokens enable row level security;
revoke all privileges on table public.registration_tokens
  from public, anon, authenticated;
grant all privileges on table public.registration_tokens to service_role;

comment on table public.registration_tokens is
  'One-time email-link tokens for claiming an existing usersData profile. Raw tokens are never stored; only SHA-256 hashes.';

notify pgrst, 'reload schema';
commit;
