-- ============================================================================
-- Path Finder — recommended books for every subject in the curriculum.
--
-- The registrar's prospectus becomes three reference tables:
--   curriculum_programs   the degree programs (BSCS, BSEd-MATH, …)
--   curriculum_subjects   every subject (course code + title)
--   curriculum_entries    where each subject sits (program × year × semester)
--
-- subject_recommendations holds the books shown to students, keyed by COURSE
-- CODE so shared courses (MATH101 in every program) share one list:
--   * librarians / admins add books directly      -> approved at once
--   * faculty suggest books from the catalog      -> pending review
--   * librarians approve or reject; the faculty member is notified
--
-- All four tables are RPC-only (no client policies), matching the
-- member_change_requests pattern. Every read is member-visible; every write
-- is guarded by role inside the RPC.
-- ============================================================================
begin;

-- ---------------------------------------------------------------------------
-- Tables
-- ---------------------------------------------------------------------------
create table if not exists public.curriculum_programs (
  id bigint generated by default as identity primary key,
  program_id bigint references public.programs(id) on delete set null,
  code text not null unique,
  name text not null,
  department text,
  director text,
  total_units int,
  created_at timestamptz not null default now()
);

create table if not exists public.curriculum_subjects (
  id bigint generated by default as identity primary key,
  course_code text not null,
  course_title text not null
);
create index if not exists curriculum_subjects_code_idx
  on public.curriculum_subjects (upper(btrim(course_code)));

create table if not exists public.curriculum_entries (
  id bigint generated by default as identity primary key,
  curriculum_program_id bigint not null references public.curriculum_programs(id) on delete cascade,
  subject_id bigint not null references public.curriculum_subjects(id) on delete cascade,
  year_level int not null check (year_level between 1 and 6),
  semester int not null check (semester between 1 and 3),
  lec_hours int,
  lab_hours int,
  units int not null,
  prerequisites text,
  remarks text
);
create unique index if not exists curriculum_entries_unique
  on public.curriculum_entries (curriculum_program_id, subject_id, year_level, semester);
create index if not exists curriculum_entries_subject_idx
  on public.curriculum_entries (subject_id);
create index if not exists curriculum_entries_program_idx
  on public.curriculum_entries (curriculum_program_id, year_level, semester);

create table if not exists public.subject_recommendations (
  id bigint generated always as identity primary key,
  course_code text not null,
  book_id bigint not null references public.books(id) on delete cascade,
  source text not null check (source in ('librarian', 'faculty')),
  note text,
  status text not null default 'pending'
    check (status in ('pending', 'approved', 'rejected')),
  recommended_by bigint not null references public."usersData"(id) on delete restrict,
  reviewed_by bigint references public."usersData"(id) on delete restrict,
  reviewed_at timestamptz,
  review_note text,
  created_at timestamptz not null default now()
);
create unique index if not exists subject_recommendations_live_unique
  on public.subject_recommendations (course_code, book_id)
  where status in ('pending', 'approved');
create index if not exists subject_recommendations_code_idx
  on public.subject_recommendations (course_code, status);
create index if not exists subject_recommendations_queue_idx
  on public.subject_recommendations (status, created_at desc);

alter table public.curriculum_programs enable row level security;
alter table public.curriculum_subjects enable row level security;
alter table public.curriculum_entries enable row level security;
alter table public.subject_recommendations enable row level security;
revoke all privileges on table public.curriculum_programs, public.curriculum_subjects,
  public.curriculum_entries, public.subject_recommendations from public, anon, authenticated;
grant all privileges on table public.curriculum_programs, public.curriculum_subjects,
  public.curriculum_entries, public.subject_recommendations to service_role;
-- No client policies: only the RPCs below read or write these tables.

-- ---------------------------------------------------------------------------
-- Internal helpers
-- ---------------------------------------------------------------------------
-- Librarian / admin profile for the caller (curation is a librarian job;
-- staff can browse but not add).
create or replace function lirc_private.path_finder_curator_id()
returns bigint
language sql
stable
security definer
set search_path = ''
as $$
  select u.id from public."usersData" u
  where u.user_id = (select auth.uid())
    and lower(btrim(u.role::text)) in ('librarian', 'admin')
  limit 1;
$$;
revoke all on function lirc_private.path_finder_curator_id() from public, anon, authenticated;

-- Faculty profile for the caller (only faculty can suggest books).
create or replace function lirc_private.path_finder_faculty_id()
returns bigint
language sql
stable
security definer
set search_path = ''
as $$
  select u.id from public."usersData" u
  where u.user_id = (select auth.uid())
    and lower(btrim(u.role::text)) = 'faculty'
  limit 1;
$$;
revoke all on function lirc_private.path_finder_faculty_id() from public, anon, authenticated;

-- One book as the Path Finder shows it: identity, shelf and live availability.
create or replace function lirc_private.path_finder_book_json(p_book_id bigint)
returns jsonb
language sql
stable
security definer
set search_path = ''
as $$
  select jsonb_build_object(
    'book_id', b.id,
    'book_name', b.book_name,
    'author', b.author,
    'isbn', b.isbn,
    'book_image', b.book_image,
    'call_number', b.call_number,
    'shelf', sh.name,
    'copies', (select count(*) from public.book_accession_numbers a where a.book_id = b.id),
    'available', (select count(*) from public.book_accession_numbers a
                  where a.book_id = b.id
                    and not exists (select 1 from public.book_loans l
                                    where l.accession_id = a.id and l.returned_at is null))
  )
  from public.books b
  left join public.shelves sh on sh.id = b.shelf_id
  where b.id = p_book_id;
$$;
revoke all on function lirc_private.path_finder_book_json(bigint) from public, anon, authenticated;

-- Bell alerts for the library team (librarians and admins with accounts).
create or replace function lirc_private.notify_library_team(
  p_type text, p_title text, p_message text, p_link text)
returns void
language sql
security definer
set search_path = ''
as $$
  insert into public.notifications (user_profile_id, type, title, message, link)
  select u.id, p_type, p_title, p_message, p_link
  from public."usersData" u
  where lower(btrim(u.role::text)) in ('librarian', 'admin');
$$;
revoke all on function lirc_private.notify_library_team(text,text,text,text) from public, anon, authenticated;

-- A suggestion row as the lists show it (subject + book + people + decision).
create or replace function lirc_private.path_finder_suggestion_json(p_row public.subject_recommendations)
returns jsonb
language sql
stable
security definer
set search_path = ''
as $$
  select lirc_private.path_finder_book_json(p_row.book_id)
    || jsonb_build_object(
      'id', p_row.id,
      'course_code', p_row.course_code,
      'course_title', (
        select s.course_title from public.curriculum_subjects s
        where upper(btrim(s.course_code)) = p_row.course_code
        order by s.id limit 1),
      'status', p_row.status,
      'source', p_row.source,
      'note', p_row.note,
      'created_at', p_row.created_at,
      'reviewed_at', p_row.reviewed_at,
      'review_note', p_row.review_note,
      'recommended_by_name', (
        select btrim(u.first_name || ' ' || u.surname) from public."usersData" u
        where u.id = p_row.recommended_by),
      'reviewed_by_name', (
        select btrim(u.first_name || ' ' || u.surname) from public."usersData" u
        where u.id = p_row.reviewed_by)
    );
$$;
revoke all on function lirc_private.path_finder_suggestion_json(public.subject_recommendations) from public, anon, authenticated;

-- ---------------------------------------------------------------------------
-- RPC: the programs list (member-visible)
-- ---------------------------------------------------------------------------
create or replace function public.lirc_path_finder_programs()
returns jsonb
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce(jsonb_agg(jsonb_build_object(
    'id', cp.id,
    'code', cp.code,
    'name', cp.name,
    'department', cp.department,
    'director', cp.director,
    'total_units', cp.total_units,
    'program_id', cp.program_id,
    'library_program', p.name,
    'department_id', p.department_id,
    'subjects', (
      select count(distinct upper(btrim(s.course_code)))
      from public.curriculum_entries e
      join public.curriculum_subjects s on s.id = e.subject_id
      where e.curriculum_program_id = cp.id),
    'covered', (
      select count(distinct upper(btrim(s.course_code)))
      from public.curriculum_entries e
      join public.curriculum_subjects s on s.id = e.subject_id
      where e.curriculum_program_id = cp.id
        and exists (
          select 1 from public.subject_recommendations r
          where r.course_code = upper(btrim(s.course_code)) and r.status = 'approved')),
    'pending', (
      select count(*) from public.subject_recommendations r
      where r.status = 'pending'
        and r.course_code in (
          select distinct upper(btrim(s.course_code))
          from public.curriculum_entries e
          join public.curriculum_subjects s on s.id = e.subject_id
          where e.curriculum_program_id = cp.id))
  ) order by cp.code), '[]'::jsonb)
  from public.curriculum_programs cp
  left join public.programs p on p.id = cp.program_id;
$$;

-- ---------------------------------------------------------------------------
-- RPC: one program's curriculum, year -> semester -> subject -> books
-- (member-visible; "my_pending" and "pending_count" fill in per role)
-- ---------------------------------------------------------------------------
create or replace function public.lirc_path_finder_curriculum(p_program_id bigint)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_faculty bigint := lirc_private.path_finder_faculty_id();
  v_curator bigint := lirc_private.path_finder_curator_id();
  v_program jsonb;
  v_years jsonb;
begin
  select jsonb_build_object(
    'id', cp.id, 'code', cp.code, 'name', cp.name,
    'department', cp.department, 'director', cp.director,
    'total_units', cp.total_units, 'library_program', p.name)
  into v_program
  from public.curriculum_programs cp
  left join public.programs p on p.id = cp.program_id
  where cp.id = p_program_id;
  if v_program is null then
    raise exception 'Program not found.';
  end if;

  select coalesce(jsonb_agg(jsonb_build_object(
      'year_level', y.year_level,
      'semesters', y.semesters
    ) order by y.year_level), '[]'::jsonb)
  into v_years
  from (
    select ey.year_level,
           jsonb_agg(jsonb_build_object('semester', ey.semester, 'subjects', ey.subjects)
                     order by ey.semester) as semesters
    from (
      select e.year_level, e.semester,
             jsonb_agg(jsonb_build_object(
               'entry_id', e.id,
               'subject_id', s.id,
               'course_code', s.course_code,
               'course_title', s.course_title,
               'units', e.units,
               'lec_hours', e.lec_hours,
               'lab_hours', e.lab_hours,
               'prerequisites', e.prerequisites,
               'remarks', e.remarks,
               'books', coalesce((
                 select jsonb_agg(rr.row_json order by rr.created_at)
                 from (
                   select lirc_private.path_finder_book_json(r.book_id)
                          || jsonb_build_object(
                               'recommendation_id', r.id,
                               'source', r.source,
                               'note', r.note) as row_json,
                          r.created_at
                   from public.subject_recommendations r
                   where r.course_code = upper(btrim(s.course_code))
                     and r.status = 'approved'
                 ) rr
               ), '[]'::jsonb),
               'my_pending', case when v_faculty is null then null else (
                 select jsonb_build_object(
                   'recommendation_id', r.id,
                   'book_name', b.book_name,
                   'created_at', r.created_at)
                 from public.subject_recommendations r
                 join public.books b on b.id = r.book_id
                 where r.course_code = upper(btrim(s.course_code))
                   and r.recommended_by = v_faculty
                   and r.status = 'pending'
                 order by r.created_at limit 1) end,
               'pending_count', case when v_curator is null then 0 else (
                 select count(*) from public.subject_recommendations r
                 where r.course_code = upper(btrim(s.course_code))
                   and r.status = 'pending') end
             ) order by s.course_code) as subjects
      from public.curriculum_entries e
      join public.curriculum_subjects s on s.id = e.subject_id
      where e.curriculum_program_id = p_program_id
      group by e.year_level, e.semester
    ) ey
    group by ey.year_level
  ) y;

  return jsonb_build_object('program', v_program, 'years', v_years);
end;
$$;

-- ---------------------------------------------------------------------------
-- RPC: the suggestions tab (faculty see their own; operators see the queue)
-- ---------------------------------------------------------------------------
create or replace function public.lirc_path_finder_suggestions()
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_faculty bigint := lirc_private.path_finder_faculty_id();
  v_curator bigint := lirc_private.path_finder_curator_id();
begin
  if v_faculty is not null then
    return jsonb_build_object(
      'role', 'faculty',
      'mine', coalesce((
        select jsonb_agg(lirc_private.path_finder_suggestion_json(r)
                         order by r.created_at desc)
        from public.subject_recommendations r
        where r.recommended_by = v_faculty), '[]'::jsonb));
  end if;
  if v_curator is not null then
    return jsonb_build_object(
      'role', 'operator',
      'pending', coalesce((
        select jsonb_agg(lirc_private.path_finder_suggestion_json(r)
                         order by r.created_at)
        from public.subject_recommendations r
        where r.status = 'pending'), '[]'::jsonb),
      'decided', coalesce((
        select jsonb_agg(lirc_private.path_finder_suggestion_json(r)
                         order by r.reviewed_at desc)
        from (
          select * from public.subject_recommendations
          where status in ('approved', 'rejected') and source = 'faculty'
          order by reviewed_at desc limit 50
        ) r), '[]'::jsonb));
  end if;
  raise exception 'Path Finder suggestions are for faculty and library staff.'
    using errcode = '42501';
end;
$$;

-- ---------------------------------------------------------------------------
-- RPC: librarian / admin adds a book directly (approved at once)
-- ---------------------------------------------------------------------------
create or replace function public.lirc_path_finder_add_recommendation(
  p_course_code text, p_book_id bigint, p_note text default null)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_curator bigint := lirc_private.path_finder_curator_id();
  v_code text := upper(btrim(coalesce(p_course_code, '')));
  v_note text := nullif(btrim(coalesce(p_note, '')), '');
  v_id bigint;
begin
  if v_curator is null then
    raise exception 'Library staff access required.' using errcode = '42501';
  end if;
  if v_code = '' or not exists (
    select 1 from public.curriculum_subjects s
    where upper(btrim(s.course_code)) = v_code) then
    raise exception 'Subject not found in the curriculum.';
  end if;
  if not exists (select 1 from public.books b where b.id = p_book_id) then
    raise exception 'Book not found in the catalog.';
  end if;
  if v_note is not null and length(v_note) > 300 then
    raise exception 'Keep the note under 300 characters.';
  end if;
  if exists (
    select 1 from public.subject_recommendations r
    where r.course_code = v_code and r.book_id = p_book_id
      and r.status in ('pending', 'approved')) then
    raise exception 'This book is already on the subject''s list.';
  end if;
  insert into public.subject_recommendations
    (course_code, book_id, source, note, status, recommended_by, reviewed_by, reviewed_at)
  values
    (v_code, p_book_id, 'librarian', v_note, 'approved', v_curator, v_curator, now())
  returning id into v_id;
  return jsonb_build_object('id', v_id, 'status', 'approved');
end;
$$;

-- ---------------------------------------------------------------------------
-- RPC: faculty suggests a book (pending until a librarian reviews it)
-- ---------------------------------------------------------------------------
create or replace function public.lirc_path_finder_suggest(
  p_course_code text, p_book_id bigint, p_note text default null)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_faculty bigint := lirc_private.path_finder_faculty_id();
  v_code text := upper(btrim(coalesce(p_course_code, '')));
  v_note text := nullif(btrim(coalesce(p_note, '')), '');
  v_id bigint;
  v_name text;
  v_book text;
begin
  if v_faculty is null then
    raise exception 'Only faculty accounts can suggest books.' using errcode = '42501';
  end if;
  if v_code = '' or not exists (
    select 1 from public.curriculum_subjects s
    where upper(btrim(s.course_code)) = v_code) then
    raise exception 'Subject not found in the curriculum.';
  end if;
  select b.book_name into v_book from public.books b where b.id = p_book_id;
  if v_book is null then
    raise exception 'Book not found in the catalog.';
  end if;
  if v_note is not null and length(v_note) > 300 then
    raise exception 'Keep the note under 300 characters.';
  end if;
  if exists (
    select 1 from public.subject_recommendations r
    where r.course_code = v_code and r.book_id = p_book_id
      and r.status in ('pending', 'approved')) then
    raise exception 'This book is already on the subject''s list.';
  end if;
  insert into public.subject_recommendations
    (course_code, book_id, source, note, status, recommended_by)
  values
    (v_code, p_book_id, 'faculty', v_note, 'pending', v_faculty)
  returning id into v_id;

  select btrim(u.first_name || ' ' || u.surname) into v_name
  from public."usersData" u where u.id = v_faculty;
  perform lirc_private.notify_library_team(
    'path_finder_suggestion',
    'New book suggestion',
    format('%s suggested "%s" for %s.', v_name, v_book, v_code),
    '/path-finder?tab=suggestions');
  return jsonb_build_object('id', v_id, 'status', 'pending');
end;
$$;

-- ---------------------------------------------------------------------------
-- RPC: librarian / admin approves or rejects a suggestion
-- ---------------------------------------------------------------------------
create or replace function public.lirc_path_finder_review(
  p_recommendation_id bigint, p_approve boolean, p_note text default null)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_curator bigint := lirc_private.path_finder_curator_id();
  v_note text := nullif(btrim(coalesce(p_note, '')), '');
  v_row public.subject_recommendations%ROWTYPE;
  v_book text;
begin
  if v_curator is null then
    raise exception 'Library staff access required.' using errcode = '42501';
  end if;
  select * into v_row from public.subject_recommendations
  where id = p_recommendation_id;
  if not found then
    raise exception 'Suggestion not found.';
  end if;
  if v_row.status <> 'pending' then
    raise exception 'This suggestion was already reviewed.';
  end if;
  if v_note is not null and length(v_note) > 300 then
    raise exception 'Keep the note under 300 characters.';
  end if;
  update public.subject_recommendations
  set status = case when p_approve then 'approved' else 'rejected' end,
      reviewed_by = v_curator,
      reviewed_at = now(),
      review_note = v_note
  where id = p_recommendation_id;

  select b.book_name into v_book from public.books b where b.id = v_row.book_id;
  perform lirc_private.notify_profile(
    v_row.recommended_by,
    case when p_approve then 'path_finder_approved' else 'path_finder_rejected' end,
    case when p_approve then 'Book suggestion approved' else 'Book suggestion not added' end,
    case when p_approve
      then format('"%s" is now recommended for %s.', v_book, v_row.course_code)
      else format('"%s" was not added to %s.%s', v_book, v_row.course_code,
                  case when v_note is null then '' else ' Note: ' || v_note end)
    end,
    '/path-finder?tab=suggestions');
  return jsonb_build_object(
    'id', p_recommendation_id,
    'status', case when p_approve then 'approved' else 'rejected' end);
end;
$$;

-- ---------------------------------------------------------------------------
-- RPC: librarian / admin removes a recommendation (any status)
-- ---------------------------------------------------------------------------
create or replace function public.lirc_path_finder_remove(p_recommendation_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_curator bigint := lirc_private.path_finder_curator_id();
begin
  if v_curator is null then
    raise exception 'Library staff access required.' using errcode = '42501';
  end if;
  delete from public.subject_recommendations where id = p_recommendation_id;
  if not found then
    raise exception 'Recommendation not found.';
  end if;
  return jsonb_build_object('removed', p_recommendation_id);
end;
$$;

-- ---------------------------------------------------------------------------
-- RPC: faculty withdraws their own pending suggestion
-- ---------------------------------------------------------------------------
create or replace function public.lirc_path_finder_withdraw(p_recommendation_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_faculty bigint := lirc_private.path_finder_faculty_id();
begin
  if v_faculty is null then
    raise exception 'Only faculty accounts can withdraw suggestions.' using errcode = '42501';
  end if;
  delete from public.subject_recommendations
  where id = p_recommendation_id
    and recommended_by = v_faculty
    and status = 'pending';
  if not found then
    raise exception 'Only your own pending suggestion can be withdrawn.';
  end if;
  return jsonb_build_object('withdrawn', p_recommendation_id);
end;
$$;

